document.addEventListener('DOMContentLoaded', function() {
    const markers = document.querySelectorAll('[data-target]');
    const defaultContent = document.getElementById('default-content');
    const dynamicContent = document.getElementById('dynamic-content');
    const closeBtn = document.getElementById('close-info');
    const objectTitle = document.getElementById('object-title');
    const objectDescription = document.getElementById('object-description');
    const objectImage = document.getElementById('object-image');
    const imageContainer = document.getElementById('object-image-container');

    // Переменные для перетаскивания изображения
    let isDragging = false;
    let offsetX, offsetY;

    // Функция для загрузки изображения
    function loadImage(src) {
        objectImage.src = src;
        objectImage.style.display = 'block';
    }

    // Обработчики для маркеров
    const detailsButton = document.getElementById('knopika');

    markers.forEach(marker => {
        marker.addEventListener('click', function() {
            const target = this.getAttribute('data-target');
            const info = infoData[target] || {
                title: "Объект",
                description: "Информация об этом объекте отсутствует.",
                image: "",
                link: "#"
            };
            
            objectTitle.textContent = info.title;
            objectDescription.textContent = info.description;
            
            if (info.image) {
                loadImage(info.image);
            } else {
                objectImage.style.display = 'none';
            }
            
            // Устанавливаем ссылку для кнопки
            detailsButton.onclick = function() {
                window.location.href = info.link;
            };
            
            defaultContent.style.display = 'none';
            dynamicContent.classList.remove('hidden');

            // Прячем кнопку, если это дом персонала
            if (target === "personal") {
                detailsButton.style.display = "none";
            } else {
                detailsButton.style.display = "block";
            }
        });
    });

    // Обработчик для кнопки закрытия
    closeBtn.addEventListener('click', function() {
        dynamicContent.classList.add('hidden');
        defaultContent.style.display = 'block';
    });

    // Обработчики для перетаскивания изображения
    objectImage.addEventListener('mousedown', function(e) {
        isDragging = true;
        offsetX = e.clientX - objectImage.getBoundingClientRect().left;
        offsetY = e.clientY - objectImage.getBoundingClientRect().top;
        objectImage.style.cursor = 'grabbing';
    });

    document.addEventListener('mousemove', function(e) {
        if (!isDragging) return;
        
        const containerRect = imageContainer.getBoundingClientRect();
        let x = e.clientX - containerRect.left - offsetX;
        let y = e.clientY - containerRect.top - offsetY;
        
        // Ограничение перемещения внутри контейнера
        x = Math.max(0, Math.min(x, containerRect.width - objectImage.width));
        y = Math.max(0, Math.min(y, containerRect.height - objectImage.height));
        
        objectImage.style.left = x + 'px';
        objectImage.style.top = y + 'px';
        objectImage.style.position = 'absolute';
    });

    document.addEventListener('mouseup', function() {
        isDragging = false;
        objectImage.style.cursor = 'grab';
    });
});



